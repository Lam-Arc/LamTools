// @vitest-environment node
import { describe, expect, it } from 'vitest'
import { createServer } from 'vite'
import { chromium } from 'playwright'

// user:“直接渲染项目真实组件…交互测试”+(分屏预览使用本地标签与布局)。
describe('split workspace gallery', () => {
  it('switches tabs and resizes the actual split workspace', async () => {
    const server = await createServer({ configFile: 'vite.config.ts', server: { port: 0 } }); await server.listen()
    const browser = await chromium.launch({ headless: true })
    try {
      const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } }); page.setDefaultTimeout(10000)
      await page.addInitScript(() => localStorage.setItem('gallery-split', 'untouched'))
      await page.goto(server.resolvedUrls!.local[0] + 'design-system.html')
      await page.getByLabel('搜索组件').fill('CoreSplitWorkspace')
      const split = page.locator('[data-gallery-split]')
      const tabs = split.getByRole('tablist', { name: '分屏标签' }); await tabs.waitFor()
      const first = tabs.getByRole('tab', { name: '示例文档' }); const second = tabs.getByRole('tab', { name: '示例笔记' })
      await first.click(); expect(await first.getAttribute('aria-selected')).toBe('true')
      await first.press('ArrowRight'); expect(await second.getAttribute('aria-selected')).toBe('true')
      expect(await split.getByRole('tabpanel').filter({ visible: true }).innerText()).toContain('已保存')
      const divider = split.getByRole('separator', { name: '调整分屏大小' }); const before = await divider.getAttribute('aria-valuenow')
      await divider.focus(); await divider.press('ArrowRight')
      expect(await divider.getAttribute('aria-valuenow')).not.toBe(before)
      await split.getByRole('button', { name: '关闭 示例文档' }).click()
      expect(await tabs.getByRole('tab').count()).toBe(1)
      expect(await second.getAttribute('aria-selected')).toBe('true')
      await split.getByRole('button', { name: '打开内容' }).click()
      await page.getByRole('menuitem', { name: '文本编辑器' }).click()
      expect(await tabs.getByRole('tab', { name: '未命名' }).getAttribute('aria-selected')).toBe('true')
      await split.getByRole('button', { name: '打开内容' }).click({ button: 'right' })
      await page.locator('[data-context-menu-panel="root"]').dispatchEvent('scroll')
      expect(await page.getByRole('menuitem', { name: '布局' }).count()).toBe(1)
      await page.getByRole('menuitem', { name: '布局' }).hover()
      await page.getByRole('menuitem', { name: '左主右双' }).click()
      expect(await split.locator('.split-pane-frame:visible').count()).toBe(2)
      const movingTab = split.getByRole('tab', { name: '未命名' })
      const contentId = await movingTab.getAttribute('aria-controls')
      const editor = split.locator(`[id="${contentId}"] .cm-content`)
      await editor.fill('拖动前的草稿')
      const emptyPane = split.locator('.split-pane-frame').filter({ has: page.locator('.split-empty') })
      const targetIndex = await emptyPane.evaluate(el => [...el.parentElement!.querySelectorAll('.split-pane-frame')].indexOf(el))
      const targetPane = split.locator('.split-pane-frame').nth(targetIndex)
      const from = (await movingTab.boundingBox())!; const to = (await targetPane.boundingBox())!
      await page.mouse.move(from.x + 10, from.y + from.height / 2); await page.mouse.down()
      await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 20 }); await page.mouse.up()
      expect(await targetPane.getByRole('tab', { name: '未命名' }).getAttribute('aria-selected')).toBe('true')
      expect(await targetPane.getByRole('tab', { name: '未命名' }).getAttribute('aria-controls')).toBe(contentId)
      expect(await split.locator(`[id="${contentId}"]`).innerText()).toContain('未命名')
      expect(await editor.innerText()).toContain('拖动前的草稿')
      await split.locator('.split-divider[aria-orientation="horizontal"]').click({ button: 'right' })
      await page.getByRole('menuitem', { name: '合并这两块分屏' }).click()
      expect(await split.locator('.split-pane-frame:visible').count()).toBe(1)
      expect(await split.getByRole('tab', { name: '未命名' }).getAttribute('aria-controls')).toBe(contentId)
      expect(await split.getByRole('tab', { name: '示例笔记' }).count()).toBe(1)
      await split.getByRole('tab', { name: '未命名' }).click()
      expect(await editor.innerText()).toContain('拖动前的草稿')
      await split.getByRole('button', { name: '关闭 未命名' }).click()
      const guard = page.getByRole('dialog', { name: '保存修改？' }); await guard.waitFor()
      await guard.getByRole('button', { name: '取消' }).click()
      expect(await editor.innerText()).toContain('拖动前的草稿')
      await split.locator(`[id="${contentId}"] input[aria-label="文件保存路径"]`).fill('草稿.md')
      await split.locator(`[id="${contentId}"] button[aria-label="保存文件"]`).click()
      await page.waitForFunction(id => document.getElementById(id!)?.textContent?.includes('已保存'), contentId)
      expect(await split.getByRole('tab', { name: '草稿.md' }).count()).toBe(1)
      expect(await page.evaluate(() => Object.keys(localStorage).some(key => key.startsWith('lamtools:split-draft:')))).toBe(false)
      await split.getByRole('button', { name: '打开内容' }).click()
      await page.evaluate(() => document.dispatchEvent(new Event('scroll')))
      expect(await page.getByRole('menuitem', { name: '文本编辑器' }).count()).toBe(0)
      await page.getByLabel('搜索组件').fill('nothing-matches')
      expect(await page.evaluate(() => localStorage.getItem('gallery-split'))).toBe('untouched')
    } finally { await browser.close(); await server.close() }
  }, 60000)
})
