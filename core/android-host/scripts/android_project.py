#!/usr/bin/env python3
"""One entry point for the Android project: initialise, inject, build, verify.

Why this exists. Most of `src-tauri/gen/android` is generated by `tauri android init`
and is disposable, but the two Kotlin files that carry the Activity callbacks are
hand-written. Keeping them only inside `gen/` made them invisible to review and put
them one regenerate away from being lost; tracking them there meant depending on a
directory the build is supposed to be free to throw away. They live in `android-src/`
now, and this script is what puts them back.

Commands
    sync      copy android-src into the generated project
    ensure    init the generated project when it is missing, then sync
    build     ensure, build an APK, optionally sign it
    verify    assert the APK really contains the bridge class and the Rust library
    all       ensure, build, verify

`sync` is idempotent and never deletes. A file whose bytes already match is left
untouched, so running it before every build does not invalidate the Kotlin compile.

Exit codes are meant to be read by a caller, so a failure says which kind it was
without anyone parsing the log:

    0  ok
    2  the environment is incomplete (SDK, NDK, JDK, node or the tauri CLI)
    3  the generated project is not the shape this script expects
    4  the build itself failed

Typical use:

    python scripts/android_project.py all --debug --target x86_64
    python scripts/android_project.py build --release --target aarch64 --sign
"""

from __future__ import annotations

import argparse
import glob
import os
import shutil
import subprocess
import sys
import time
import zipfile
from pathlib import Path

EXIT_OK = 0
EXIT_ENV = 2
EXIT_PROJECT = 3
EXIT_BUILD = 4

APP_DIR = Path(__file__).resolve().parent.parent
SRC_ROOT = APP_DIR / "android-src"
PROJECT = APP_DIR / "src-tauri/gen/android"
JAVA_ROOT = PROJECT / "app/src/main/java"
DEFAULT_TIMEOUT = 1800


def say(message: str) -> None:
    print(f"[android] {message}", flush=True)


def fail(code: int, message: str) -> int:
    print(f"[android] {message}", file=sys.stderr, flush=True)
    return code


# --------------------------------------------------------------------- environment


def find_android_home() -> Path | None:
    for candidate in (
        os.environ.get("ANDROID_HOME"),
        os.environ.get("ANDROID_SDK_ROOT"),
        r"E:\Environment\AndroidSDK",
        str(Path.home() / "Android/Sdk"),
        "/usr/local/lib/android/sdk",
    ):
        if candidate and (Path(candidate) / "platform-tools").exists():
            return Path(candidate)
    return None


def find_ndk(android_home: Path) -> Path | None:
    for var in ("ANDROID_NDK_HOME", "NDK_HOME", "NDK_ROOT"):
        value = os.environ.get(var)
        if value and Path(value).exists():
            return Path(value)
    ndk_root = android_home / "ndk"
    if not ndk_root.exists():
        return None
    versions = sorted(
        (entry for entry in ndk_root.iterdir() if entry.is_dir()),
        key=lambda entry: entry.name,
    )
    return versions[-1] if versions else None


def find_java_home() -> Path | None:
    value = os.environ.get("JAVA_HOME")
    if value and Path(value).exists():
        return Path(value)
    patterns = (
        "C:/Program Files/Microsoft/jdk-17*",
        "C:/Program Files/Java/jdk-17*",
        "/usr/lib/jvm/*17*",
    )
    for pattern in patterns:
        matches = sorted(Path(p) for p in glob.glob(pattern) if Path(p).is_dir())
        if matches:
            return matches[-1]
    return None


def tauri_cli() -> list[str] | None:
    """The command prefix that runs the tauri CLI, or None."""
    explicit = os.environ.get("TAURI_CLI")
    if explicit:
        path = Path(explicit)
        if path.suffix == ".js":
            return ["node", str(path)]
        return [str(path)]

    # The desktop project already has the CLI installed; reuse it rather than
    # downloading a second copy.
    for candidate in (
        APP_DIR.parent / "desktop/node_modules/@tauri-apps/cli/tauri.js",
        APP_DIR / "node_modules/@tauri-apps/cli/tauri.js",
    ):
        if candidate.exists():
            node = shutil.which("node")
            if node:
                return [node, str(candidate)]
    return None


def environment() -> tuple[dict[str, str] | None, list[str] | None]:
    """The environment the build needs, or the reasons it cannot run."""
    problems: list[str] = []
    android_home = find_android_home()
    if not android_home:
        problems.append("no Android SDK: set ANDROID_HOME")
    ndk = find_ndk(android_home) if android_home else None
    if android_home and not ndk:
        problems.append(f"no NDK under {android_home / 'ndk'}")
    java_home = find_java_home()
    if not java_home:
        problems.append("no JDK 17: set JAVA_HOME")
    cli = tauri_cli()
    if not cli:
        problems.append(
            "no tauri CLI: run `npm i` in core/desktop, or set TAURI_CLI to tauri.js"
        )
    if problems:
        for problem in problems:
            print(f"[android] {problem}", file=sys.stderr)
        return None, problems

    env = dict(os.environ)
    env["ANDROID_HOME"] = str(android_home)
    env["ANDROID_SDK_ROOT"] = str(android_home)
    env["NDK_HOME"] = str(ndk)
    env["JAVA_HOME"] = str(java_home)
    # Gradle wants the JDK on PATH in some configurations.
    env["PATH"] = f"{java_home / 'bin'}{os.pathsep}{env.get('PATH', '')}"
    env["TAURI_ANDROID_BUILD_ARGS"] = ""
    return env, None


# --------------------------------------------------------------------- sync


def sync_sources() -> int:
    if not SRC_ROOT.exists():
        return fail(EXIT_PROJECT, f"{SRC_ROOT} does not exist")
    if not JAVA_ROOT.exists():
        return fail(
            EXIT_PROJECT,
            f"{JAVA_ROOT} does not exist: run `ensure` first, or the generated "
            "project changed shape and this script needs updating",
        )

    written = 0
    unchanged = 0
    for path in sorted(SRC_ROOT.rglob("*.kt")):
        relative = path.relative_to(SRC_ROOT)
        target = JAVA_ROOT / relative
        data = path.read_bytes()
        if target.exists() and target.read_bytes() == data:
            unchanged += 1
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        written += 1

    say(f"sync: {written} written, {unchanged} unchanged, into {JAVA_ROOT}")
    return EXIT_OK


# --------------------------------------------------------------------- ensure


def fix_generated_node_path() -> None:
    """Repairs the node path `tauri android init` bakes into the generated buildSrc.

    The template writes the absolute node binary it detected, extension included and
    in whatever case it happened to be spelled. Gradle then treats `node.EXE` as an
    unknown executable, appends `.bat`, and fails with

        A problem occurred starting process 'command '...\node.EXE.bat''

    which is a build that cannot start for a reason that has nothing to do with the
    code being built. Every other machine that spells it `node.exe` builds fine, so
    this looks like an environment problem until it is read closely.

    Rewriting it to the bare command name lets the OS resolve `node` through PATH,
    which is what the generated fallbacks already assume.
    """
    build_task = PROJECT / "buildSrc/src/main/java/com/lamtools/sunday/core/kotlin/BuildTask.kt"
    if not build_task.exists():
        return
    text = build_task.read_text(encoding="utf-8")
    marker = 'val executable = """'
    start = text.find(marker)
    if start < 0:
        return
    end = text.find('"""', start + len(marker))
    if end < 0:
        return
    current = text[start + len(marker):end]
    if current.strip() == "node":
        return
    fixed = text[:start] + marker + "node" + text[end:]
    build_task.write_text(fixed, encoding="utf-8")
    say(f"fixed generated node path ({current} -> node)")


def ensure_project(env: dict[str, str], timeout: int) -> int:
    if PROJECT.exists():
        say("generated project already present")
        return sync_sources()

    say("generated project missing, running `tauri android init`")
    cli = tauri_cli()
    assert cli is not None
    result = run(cli + ["android", "init"], APP_DIR, env, timeout)
    if result != EXIT_OK:
        return result
    return sync_sources()


# --------------------------------------------------------------------- build


def run(command: list[str], cwd: Path, env: dict[str, str], timeout: int) -> int:
    pretty = " ".join(command)
    say(f"run: {pretty}")
    started = time.monotonic()
    try:
        completed = subprocess.run(
            command, cwd=str(cwd), env=env, timeout=timeout, text=True
        )
    except subprocess.TimeoutExpired:
        return fail(EXIT_BUILD, f"timed out after {timeout}s: {pretty}")
    say(f"exit {completed.returncode} in {time.monotonic() - started:.0f}s")
    return EXIT_OK if completed.returncode == 0 else EXIT_BUILD


def apk_candidates(debug: bool) -> list[Path]:
    """Where Gradle puts the artefact, in the order it may appear.

    A release build is unsigned and named `-unsigned`; a debug build is signed with
    the debug key by Gradle and carries no suffix. Both are named here so a caller
    never has to know which variant it asked for.
    """
    variant = "debug" if debug else "release"
    base = PROJECT / f"app/build/outputs/apk/universal/{variant}"
    return [
        base / f"app-universal-{variant}-unsigned.apk",
        base / f"app-universal-{variant}.apk",
    ]


def find_apk(debug: bool) -> Path | None:
    for candidate in apk_candidates(debug):
        if candidate.exists():
            return candidate
    return None


def apk_path(debug: bool) -> Path:
    found = find_apk(debug)
    if found is not None:
        return found
    return apk_candidates(debug)[0]


def build(env: dict[str, str], debug: bool, target: str, timeout: int) -> int:
    fix_generated_node_path()
    cli = tauri_cli()
    assert cli is not None
    command = cli + ["android", "build", "--apk", "--target", target]
    if debug:
        command.append("--debug")
    # The CLI refuses to build when the npm `@tauri-apps/api` minor differs from the
    # Rust `tauri` crate's. A fresh worktree inherits the npm tree from another
    # checkout, so that comparison can fail for reasons that have nothing to do with
    # this build. The escape hatch is explicit and off by default: turning it on
    # silently would hide a real mismatch.
    if env.get("ANDROID_IGNORE_TAURI_VERSION_MISMATCH") == "1":
        command.append("--ignore-version-mismatches")
    code = run(command, APP_DIR, env, timeout)
    if code != EXIT_OK:
        return code
    produced = apk_path(debug)
    if not produced.exists():
        return fail(EXIT_BUILD, f"the build reported success but {produced} is missing")
    say(f"apk: {produced} ({produced.stat().st_size // 1024} KB)")
    return EXIT_OK


def build_tools(android_home: Path) -> Path | None:
    root = android_home / "build-tools"
    if not root.exists():
        return None
    versions = sorted((entry for entry in root.iterdir() if entry.is_dir()), key=lambda e: e.name)
    return versions[-1] if versions else None


def sign(apk: Path, env: dict[str, str], timeout: int) -> int:
    tools = build_tools(Path(env["ANDROID_HOME"]))
    if tools is None:
        return fail(EXIT_ENV, "no build-tools directory to sign with")
    keystore = Path.home() / ".android/debug.keystore"
    if not keystore.exists():
        return fail(EXIT_ENV, f"no debug keystore at {keystore}")

    apksigner = tools / ("apksigner.bat" if os.name == "nt" else "apksigner")
    signed = apk.with_name(apk.name.replace("-unsigned", "-signed"))
    shutil.copyfile(apk, signed)
    code = run(
        [
            str(apksigner),
            "sign",
            "--ks",
            str(keystore),
            "--ks-pass",
            "pass:android",
            "--key-pass",
            "pass:android",
            "--ks-key-alias",
            "androiddebugkey",
            str(signed),
        ],
        APP_DIR,
        env,
        timeout,
    )
    if code != EXIT_OK:
        return code
    say(f"signed: {signed}")
    return EXIT_OK


# --------------------------------------------------------------------- verify


def verify(apk: Path) -> int:
    """Assert the APK carries both halves of the bridge.

    A build that compiles is not evidence that our Kotlin was injected: the project
    would happily build Tauri's own template without our Activity overrides. Checking
    the packaged artefact is the only cheap way to know.
    """
    if not apk.exists():
        return fail(EXIT_PROJECT, f"{apk} is missing")

    with zipfile.ZipFile(apk) as archive:
        names = archive.namelist()
        native = [name for name in names if name.endswith("libsunday_android_host_lib.so")]
        if not native:
            return fail(EXIT_BUILD, "the APK has no libsunday_android_host_lib.so")
        dex = [name for name in names if name.endswith(".dex")]
        if not dex:
            return fail(EXIT_BUILD, "the APK has no dex")
        blob = b"".join(archive.read(name) for name in dex)
        wanted = {
            "native library": True,
            "class LifecycleBridge (dex)": b"LifecycleBridge" in blob,
            "class MainActivity (dex)": b"MainActivity" in blob,
        }

    for what, found in wanted.items():
        say(f"verify: {what}: {'yes' if found else 'MISSING'}")
    missing = [what for what, found in wanted.items() if not found]
    if missing:
        return fail(
            EXIT_BUILD,
            "the APK is missing " + ", ".join(missing) + ": the Kotlin injection did not land",
        )
    say("verify: the APK carries the bridge and the Rust library")
    return EXIT_OK


# --------------------------------------------------------------------- main


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["sync", "ensure", "build", "verify", "all"])
    parser.add_argument("--debug", action="store_true", help="build the debug variant")
    parser.add_argument("--release", action="store_true", help="build the release variant")
    parser.add_argument("--target", default="x86_64", help="android target ABI")
    parser.add_argument("--sign", action="store_true", help="sign with the debug keystore")
    parser.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT)
    args = parser.parse_args(argv)

    if args.command == "sync":
        return sync_sources()

    env, problems = environment()
    if env is None:
        return fail(EXIT_ENV, f"environment incomplete: {len(problems or [])} problem(s)")

    if args.command == "ensure":
        return ensure_project(env, args.timeout)

    if args.command == "verify":
        # Verify the most recent artefact, whichever variant it is.
        for debug in (True, False):
            found = find_apk(debug)
            if found is not None:
                return verify(found)
        return fail(EXIT_PROJECT, "no APK to verify: run `build` first")

    debug = args.debug or not args.release

    code = ensure_project(env, args.timeout)
    if code != EXIT_OK:
        return code

    code = build(env, debug, args.target, args.timeout)
    if code != EXIT_OK:
        return code

    apk = apk_path(debug)
    code = verify(apk)
    if code != EXIT_OK:
        return code

    if args.sign:
        code = sign(apk, env, args.timeout)
        if code != EXIT_OK:
            return code

    say("done")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
