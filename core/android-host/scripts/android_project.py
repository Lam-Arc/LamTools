#!/usr/bin/env python3
"""One entry point for the Android project: initialise, inject, build, verify.

Why this exists. Most of `src-tauri/gen/android` is generated by `tauri android init`
and is disposable, but the two Kotlin files that carry the Activity callbacks are
hand-written. Keeping them only inside `gen/` made them invisible to review and put
them one regenerate away from being lost; tracking them there meant depending on a
directory the build is supposed to be free to throw away. They live in `android-src/`
now, and this script is what puts them back.

Commands
    sync      copy android-src into the generated project
    ensure    init the generated project when it is missing, then sync
    build     ensure, build an APK, optionally sign it
    verify    assert the APK really contains the bridge class and the Rust library
    all       ensure, build, verify

`sync` is idempotent and never deletes. A file whose bytes already match is left
untouched, so running it before every build does not invalidate the Kotlin compile.

Exit codes are meant to be read by a caller, so a failure says which kind it was
without anyone parsing the log:

    0  ok
    2  the environment is incomplete (SDK, NDK, JDK, node or the tauri CLI)
    3  the generated project is not the shape this script expects
    4  the build itself failed

Typical use:

    python scripts/android_project.py all --debug --target x86_64
    python scripts/android_project.py build --release --target aarch64 --sign
"""

from __future__ import annotations

import argparse
import glob
import os
import shutil
import subprocess
import sys
import time
import zipfile
from pathlib import Path

EXIT_OK = 0
EXIT_ENV = 2
EXIT_PROJECT = 3
EXIT_BUILD = 4

APP_DIR = Path(__file__).resolve().parent.parent
SRC_ROOT = APP_DIR / "android-src"
PROJECT = APP_DIR / "src-tauri/gen/android"
JAVA_ROOT = PROJECT / "app/src/main/java"
DEFAULT_TIMEOUT = 1800


def say(message: str) -> None:
    print(f"[android] {message}", flush=True)


def fail(code: int, message: str) -> int:
    print(f"[android] {message}", file=sys.stderr, flush=True)
    return code


# --------------------------------------------------------------------- environment


def find_android_home() -> Path | None:
    for candidate in (
        os.environ.get("ANDROID_HOME"),
        os.environ.get("ANDROID_SDK_ROOT"),
        r"E:\Environment\AndroidSDK",
        str(Path.home() / "Android/Sdk"),
        "/usr/local/lib/android/sdk",
    ):
        if candidate and (Path(candidate) / "platform-tools").exists():
            return Path(candidate)
    return None


def find_ndk(android_home: Path) -> Path | None:
    for var in ("ANDROID_NDK_HOME", "NDK_HOME", "NDK_ROOT"):
        value = os.environ.get(var)
        if value and Path(value).exists():
            return Path(value)
    ndk_root = android_home / "ndk"
    if not ndk_root.exists():
        return None
    versions = sorted(
        (entry for entry in ndk_root.iterdir() if entry.is_dir()),
        key=lambda entry: entry.name,
    )
    return versions[-1] if versions else None


def find_java_home() -> Path | None:
    value = os.environ.get("JAVA_HOME")
    if value and Path(value).exists():
        return Path(value)
    patterns = (
        "C:/Program Files/Microsoft/jdk-17*",
        "C:/Program Files/Java/jdk-17*",
        "/usr/lib/jvm/*17*",
    )
    for pattern in patterns:
        matches = sorted(Path(p) for p in glob.glob(pattern) if Path(p).is_dir())
        if matches:
            return matches[-1]
    return None


def tauri_cli() -> list[str] | None:
    """The command prefix that runs the tauri CLI, or None."""
    explicit = os.environ.get("TAURI_CLI")
    if explicit:
        path = Path(explicit)
        if path.suffix == ".js":
            return ["node", str(path)]
        return [str(path)]

    # The desktop project already has the CLI installed; reuse it rather than
    # downloading a second copy.
    for candidate in (
        APP_DIR.parent / "desktop/node_modules/@tauri-apps/cli/tauri.js",
        APP_DIR / "node_modules/@tauri-apps/cli/tauri.js",
    ):
        if candidate.exists():
            node = shutil.which("node")
            if node:
                return [node, str(candidate)]
    return None


def environment() -> tuple[dict[str, str] | None, list[str] | None]:
    """The environment the build needs, or the reasons it cannot run."""
    problems: list[str] = []
    android_home = find_android_home()
    if not android_home:
        problems.append("no Android SDK: set ANDROID_HOME")
    ndk = find_ndk(android_home) if android_home else None
    if android_home and not ndk:
        problems.append(f"no NDK under {android_home / 'ndk'}")
    java_home = find_java_home()
    if not java_home:
        problems.append("no JDK 17: set JAVA_HOME")
    cli = tauri_cli()
    if not cli:
        problems.append(
            "no tauri CLI: run `npm i` in core/desktop, or set TAURI_CLI to tauri.js"
        )
    if problems:
        for problem in problems:
            print(f"[android] {problem}", file=sys.stderr)
        return None, problems

    env = dict(os.environ)
    env["ANDROID_HOME"] = str(android_home)
    env["ANDROID_SDK_ROOT"] = str(android_home)
    env["NDK_HOME"] = str(ndk)
    env["JAVA_HOME"] = str(java_home)
    # Gradle wants the JDK on PATH in some configurations.
    env["PATH"] = f"{java_home / 'bin'}{os.pathsep}{env.get('PATH', '')}"
    env["TAURI_ANDROID_BUILD_ARGS"] = ""
    return env, None


# --------------------------------------------------------------------- sync


def sync_sources() -> int:
    if not SRC_ROOT.exists():
        return fail(EXIT_PROJECT, f"{SRC_ROOT} does not exist")
    if not JAVA_ROOT.exists():
        return fail(
            EXIT_PROJECT,
            f"{JAVA_ROOT} does not exist: run `ensure` first, or the generated "
            "project changed shape and this script needs updating",
        )

    written = 0
    unchanged = 0
    for path in sorted(SRC_ROOT.rglob("*.kt")):
        relative = path.relative_to(SRC_ROOT)
        target = JAVA_ROOT / relative
        data = path.read_bytes()
        if target.exists() and target.read_bytes() == data:
            unchanged += 1
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        written += 1

    say(f"sync: {written} written, {unchanged} unchanged, into {JAVA_ROOT}")
    code = sync_manifest()
    if code != EXIT_OK:
        return code
    return sync_runtime_gradle()


# --------------------------------------------------------------------- manifest

MANIFEST = PROJECT / "app/src/main/AndroidManifest.xml"

# user:"Manifest 与 XML 不会被拷进去，重新 init 会丢。所以权限与 service 声明必须写成脚本里的
# 幂等注入函数"+(标记即「已经注入过」，重复 sync 不会重复加；verify 再确认它真的进了包)。
OVERLAY_MARKER = "<!-- >>> Sunday overlay -->"

OVERLAY_PERMISSIONS = (
    # Drawing over other apps. Not requestable at runtime: it is a special app access.
    "android.permission.SYSTEM_ALERT_WINDOW",
    # The ring lives in a foreground service, otherwise the system freezes it.
    "android.permission.FOREGROUND_SERVICE",
    "android.permission.FOREGROUND_SERVICE_SPECIAL_USE",
    # Android 13+ hides a foreground notification without it; the service still runs.
    "android.permission.POST_NOTIFICATIONS",
)


def sync_manifest() -> int:
    """Injects the overlay declarations and the small-window flag into the manifest.

    `sync` only copies `*.kt`, and `tauri android init` regenerates this file, so nothing
    else would put these back after a regenerate. Every step is idempotent and marked.
    """
    if not MANIFEST.exists():
        return fail(EXIT_PROJECT, f"{MANIFEST} does not exist: run `ensure` first")
    text = MANIFEST.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in text else "\n"
    original = text
    text = inject_permissions(text, nl)
    text = inject_small_window_flag(text, nl)
    text = inject_overlay_service(text, nl)
    if text != original:
        MANIFEST.write_text(text, encoding="utf-8", newline="")
        say("sync: injected the overlay service, its permissions and the small-window flag")
    else:
        say("sync: the manifest already carries the overlay declarations")
    return EXIT_OK


def inject_permissions(text: str, nl: str) -> str:
    """Adds the permissions the ring needs, above `<application>`."""
    missing = [name for name in OVERLAY_PERMISSIONS if f'android:name="{name}"' not in text]
    if not missing:
        return text
    anchor = nl + "    <application"
    if anchor not in text:
        return text
    block = nl.join(f'    <uses-permission android:name="{name}" />' for name in missing)
    return text.replace(anchor, nl + block + nl + nl + "    <application", 1)


def inject_small_window_flag(text: str, nl: str) -> str:
    """Adds `supportsPictureInPicture` to the launcher activity.

    user:"Manifest 的 activity 加 android:supportsPictureInPicture=\"true\""+(没有这一行，
    enterPictureInPictureMode 直接返回 false，用户只会看到「不支持小窗」)。
    """
    if "supportsPictureInPicture" in text:
        return text
    name = 'android:name=".MainActivity"'
    index = text.find(name)
    if index < 0:
        return text
    closing = text.find(">", index)
    if closing < 0:
        return text
    cut = closing - 1 if text[closing - 1] == "/" else closing
    attribute = 'android:supportsPictureInPicture="true"'
    return text[:cut] + nl + "            " + attribute + text[cut:]


def inject_overlay_service(text: str, nl: str) -> str:
    """Declares the ring's foreground service, once."""
    if OVERLAY_MARKER in text:
        return text
    anchor = "    </application>"
    if anchor not in text:
        return text
    block = nl.join(
        [
            "        " + OVERLAY_MARKER,
            "        <service",
            '            android:name=".SundayOverlayService"',
            '            android:exported="false"',
            '            android:foregroundServiceType="specialUse">',
            "            <property",
            '                android:name="android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE"',
            '                android:value="floating control" />',
            "        </service>",
            "        <!-- <<< Sunday overlay -->",
            "",
        ]
    )
    return text.replace(anchor, block + anchor, 1)


# Gradle fragment the app module applies. Kept out of `android-src/com/**` because it
# is not Kotlin, and out of the generated project because regenerating would drop it.
RUNTIME_MARKER = "// >>> Sunday runtime"


def sync_runtime_gradle() -> int:
    """Injects the runtime wiring into the app module's Gradle script, once."""
    build_gradle = PROJECT / "app" / "build.gradle.kts"
    build_text = build_gradle.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in build_text else "\n"

    # An earlier design applied a separate script; that cannot reach the android {}
    # accessors, so remove the apply line if it is still there.
    stale = 'apply(from = "sunday-runtime.gradle.kts")'
    if stale in build_text:
        build_text = build_text.replace(stale, "").rstrip() + "\n"

    if RUNTIME_MARKER in build_text:
        build_gradle.write_text(build_text, encoding="utf-8")
        return EXIT_OK

    anchor = "android {"
    if anchor not in build_text:
        return fail(EXIT_PROJECT, "app/build.gradle.kts has no android block to extend")

    injected = nl.join([
        "",
        "    // >>> Sunday runtime: filled in by android_project.py, do not edit by hand.",
        "    // proot and its loader are packaged as lib*.so so Gradle extracts them into",
        "    // nativeLibraryDir at install time. Without legacy packaging the APK keeps",
        "    // them compressed and Android refuses to execute a binary from app data.",
        "    packaging {",
        "        jniLibs { useLegacyPackaging = true }",
        "    }",
        "    // One ABI per APK: the archive carries that ABI's Python, so a universal build",
        "    // would ship the wrong interpreter to half the devices.",
        "    defaultConfig {",
        "        ndk {",
        "            abiFilters.clear()",
        '            val rtAbi = System.getenv("SUNDAY_RT_ABI") ?: "x86_64"',
        '            abiFilters.add(if (rtAbi == "aarch64") "arm64-v8a" else "x86_64")',
        "        }",
        "    }",
        "    // The unpacked runtime (manifest + rootfs archive) ships as an Android asset",
        "    // and is copied to filesDir on first launch.",
        '    val sundayRuntimeAssets = System.getenv("SUNDAY_RT_ASSETS")',
        '        ?: file("../../../../../android-runtime/tools/out/x86_64/assets").absolutePath',
        '    sourceSets.getByName("main").assets.srcDir(sundayRuntimeAssets)',
        '    // proot, its loader and the two libraries it needs are packaged as lib*.so so',
        '    // Gradle extracts them into nativeLibraryDir: the only directory Android still',
        '    // executes a binary from, and a runtime without them cannot start.',
        '    val sundayRuntimeJni = File(file(sundayRuntimeAssets).parentFile, "jniLibs")',
        '    sourceSets.getByName("main").jniLibs.srcDir(sundayRuntimeJni)',
        "    // <<< Sunday runtime",
        "",
    ])
    build_text = build_text.replace(anchor, anchor + nl + injected, 1)
    build_gradle.write_text(build_text, encoding="utf-8")
    say("sync: injected the runtime wiring into app/build.gradle.kts")
    return EXIT_OK


def tauri_cli_js() -> Path | None:
    """The CLI's own JS entry point, which is what `node` must be given to run it."""
    explicit = os.environ.get("TAURI_CLI")
    if explicit:
        path = Path(explicit)
        if path.suffix == ".js" and path.exists():
            return path
        # `TAURI_CLI` may also name the launcher binary; resolve its js sibling.
        sibling = path.with_suffix(".js")
        if sibling.exists():
            return sibling
    for candidate in (
        APP_DIR / "node_modules/@tauri-apps/cli/tauri.js",
        APP_DIR.parent / "desktop/node_modules/@tauri-apps/cli/tauri.js",
    ):
        if candidate.exists():
            return candidate
    return None


def fix_generated_node_path() -> None:
    """Makes the generated Gradle task start, on Windows in particular.

    `tauri android init` writes the node binary and an argv that begins with `tauri`. That
    works only when `tauri` happens to be resolvable as a module; through `project.exec`
    it is not, and the task dies with `MODULE_NOT_FOUND` or with a fabricated
    `node.EXE.bat` path. Both were real failures here.

    The fix is to name both sides explicitly: this machine's node, and the CLI's JS entry
    point as the first argument.
    """
    build_task = PROJECT / "buildSrc/src/main/java/com/lamtools/sunday/core/kotlin/BuildTask.kt"
    if not build_task.exists():
        return
    node = shutil.which("node")
    if not node:
        return fail(EXIT_ENV, "node is not on PATH: the Tauri Gradle task cannot run")
    resolved = Path(node)
    if os.name == "nt" and resolved.suffix.lower() != ".exe":
        resolved = resolved.with_suffix(".exe")
    node_path = str(resolved).replace("\\", "/")

    cli = tauri_cli_js()
    if cli is None:
        return fail(EXIT_ENV, "the tauri CLI is not installed: set TAURI_CLI to its tauri.js")
    cli_path = str(cli).replace("\\", "/")

    text = build_task.read_text(encoding="utf-8")
    original = text

    marker = 'val executable = """'
    begin = text.find(marker)
    if begin >= 0:
        finish = text.find('"""', begin + len(marker))
        if finish >= 0:
            text = text[:begin] + marker + node_path + text[finish:]

    old_args = 'val args = listOf("tauri", "android", "android-studio-script")'
    if old_args in text:
        text = text.replace(
            old_args,
            'val args = listOf("%s", "android", "android-studio-script")' % cli_path,
            1,
        )

    if text != original:
        build_task.write_text(text, encoding="utf-8")
        say(f"fixed generated Gradle task (node={node_path}, cli={cli_path})")


def ensure_project(env: dict[str, str], timeout: int) -> int:
    if PROJECT.exists():
        say("generated project already present")
        return sync_sources()

    say("generated project missing, running `tauri android init`")
    cli = tauri_cli()
    assert cli is not None
    result = run(cli + ["android", "init"], APP_DIR, env, timeout)
    if result != EXIT_OK:
        return result
    return sync_sources()


# --------------------------------------------------------------------- build


def run(command: list[str], cwd: Path, env: dict[str, str], timeout: int) -> int:
    pretty = " ".join(command)
    say(f"run: {pretty}")
    started = time.monotonic()
    try:
        completed = subprocess.run(
            command, cwd=str(cwd), env=env, timeout=timeout, text=True
        )
    except subprocess.TimeoutExpired:
        return fail(EXIT_BUILD, f"timed out after {timeout}s: {pretty}")
    say(f"exit {completed.returncode} in {time.monotonic() - started:.0f}s")
    return EXIT_OK if completed.returncode == 0 else EXIT_BUILD


def apk_candidates(debug: bool) -> list[Path]:
    """Where Gradle puts the artefact, in the order it may appear.

    A release build is unsigned and named `-unsigned`; a debug build is signed with
    the debug key by Gradle and carries no suffix. Both are named here so a caller
    never has to know which variant it asked for.
    """
    variant = "debug" if debug else "release"
    base = PROJECT / f"app/build/outputs/apk/universal/{variant}"
    return [
        base / f"app-universal-{variant}-unsigned.apk",
        base / f"app-universal-{variant}.apk",
    ]


def find_apk(debug: bool) -> Path | None:
    for candidate in apk_candidates(debug):
        if candidate.exists():
            return candidate
    return None


def apk_path(debug: bool) -> Path:
    found = find_apk(debug)
    if found is not None:
        return found
    return apk_candidates(debug)[0]


def build(env: dict[str, str], debug: bool, target: str, timeout: int) -> int:
    fix_generated_node_path()
    cli = tauri_cli()
    assert cli is not None
    command = cli + ["android", "build", "--apk", "--target", target]
    if debug:
        command.append("--debug")
    # The CLI refuses to build when the npm `@tauri-apps/api` minor differs from the
    # Rust `tauri` crate's. A fresh worktree inherits the npm tree from another
    # checkout, so that comparison can fail for reasons that have nothing to do with
    # this build. The escape hatch is explicit and off by default: turning it on
    # silently would hide a real mismatch.
    if env.get("ANDROID_IGNORE_TAURI_VERSION_MISMATCH") == "1":
        command.append("--ignore-version-mismatches")
    code = run(command, APP_DIR, env, timeout)
    if code != EXIT_OK:
        return code
    produced = apk_path(debug)
    if not produced.exists():
        return fail(EXIT_BUILD, f"the build reported success but {produced} is missing")
    say(f"apk: {produced} ({produced.stat().st_size // 1024} KB)")
    return EXIT_OK


def build_tools(android_home: Path) -> Path | None:
    root = android_home / "build-tools"
    if not root.exists():
        return None
    versions = sorted((entry for entry in root.iterdir() if entry.is_dir()), key=lambda e: e.name)
    return versions[-1] if versions else None


def sign(apk: Path, env: dict[str, str], timeout: int) -> int:
    tools = build_tools(Path(env["ANDROID_HOME"]))
    if tools is None:
        return fail(EXIT_ENV, "no build-tools directory to sign with")
    keystore = Path.home() / ".android/debug.keystore"
    if not keystore.exists():
        return fail(EXIT_ENV, f"no debug keystore at {keystore}")

    apksigner = tools / ("apksigner.bat" if os.name == "nt" else "apksigner")
    signed = apk.with_name(apk.name.replace("-unsigned", "-signed"))
    shutil.copyfile(apk, signed)
    code = run(
        [
            str(apksigner),
            "sign",
            "--ks",
            str(keystore),
            "--ks-pass",
            "pass:android",
            "--key-pass",
            "pass:android",
            "--ks-key-alias",
            "androiddebugkey",
            str(signed),
        ],
        APP_DIR,
        env,
        timeout,
    )
    if code != EXIT_OK:
        return code
    say(f"signed: {signed}")
    return EXIT_OK


# --------------------------------------------------------------------- verify


def verify(apk: Path) -> int:
    """Assert the APK carries both halves of the bridge.

    A build that compiles is not evidence that our Kotlin was injected: the project
    would happily build Tauri's own template without our Activity overrides. Checking
    the packaged artefact is the only cheap way to know.
    """
    if not apk.exists():
        return fail(EXIT_PROJECT, f"{apk} is missing")

    with zipfile.ZipFile(apk) as archive:
        names = archive.namelist()
        native = [name for name in names if name.endswith("libsunday_android_host_lib.so")]
        if not native:
            return fail(EXIT_BUILD, "the APK has no libsunday_android_host_lib.so")
        dex = [name for name in names if name.endswith(".dex")]
        if not dex:
            return fail(EXIT_BUILD, "the APK has no dex")
        blob = b"".join(archive.read(name) for name in dex)
        wanted = {
            "native library": True,
            "class LifecycleBridge (dex)": b"LifecycleBridge" in blob,
            "class MainActivity (dex)": b"MainActivity" in blob,
            # user:"verify() 里加断言：dex 里必须出现 SundayOverlayService"+(否则构建
            # 通过但改动没进包，装上手机只会看到「没有悬浮环」)。
            "class SundayOverlayService (dex)": b"SundayOverlayService" in blob,
        }

    for what, found in wanted.items():
        say(f"verify: {what}: {'yes' if found else 'MISSING'}")
    missing = [what for what, found in wanted.items() if not found]
    if missing:
        return fail(
            EXIT_BUILD,
            "the APK is missing " + ", ".join(missing) + ": the Kotlin injection did not land",
        )
    say("verify: the APK carries the bridge and the Rust library")
    return EXIT_OK


# --------------------------------------------------------------------- main


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["sync", "ensure", "build", "verify", "all"])
    parser.add_argument("--debug", action="store_true", help="build the debug variant")
    parser.add_argument("--release", action="store_true", help="build the release variant")
    parser.add_argument("--target", default="x86_64", help="android target ABI")
    parser.add_argument("--sign", action="store_true", help="sign with the debug keystore")
    parser.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT)
    args = parser.parse_args(argv)

    if args.command == "sync":
        return sync_sources()

    env, problems = environment()
    if env is None:
        return fail(EXIT_ENV, f"environment incomplete: {len(problems or [])} problem(s)")

    if args.command == "ensure":
        return ensure_project(env, args.timeout)

    if args.command == "verify":
        # Verify the most recent artefact, whichever variant it is.
        for debug in (True, False):
            found = find_apk(debug)
            if found is not None:
                return verify(found)
        return fail(EXIT_PROJECT, "no APK to verify: run `build` first")

    debug = args.debug or not args.release

    code = ensure_project(env, args.timeout)
    if code != EXIT_OK:
        return code

    code = build(env, debug, args.target, args.timeout)
    if code != EXIT_OK:
        return code

    apk = apk_path(debug)
    code = verify(apk)
    if code != EXIT_OK:
        return code

    if args.sign:
        code = sign(apk, env, args.timeout)
        if code != EXIT_OK:
            return code

    say("done")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
