// user:“该修就修，不用停下”+(在实际运行的 Sunday 后端检验插件画布和文件操作)。
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const require = createRequire(resolve('.build/excalidraw-test/package.json'));
const { chromium } = require('playwright-core');
const base = process.env.SUNDAY_TEST_URL;

test('installed plugin draws and saves through the running Sunday host', async () => {
  assert.ok(base, 'SUNDAY_TEST_URL is required');
  const workspace = await mkdtemp(join(tmpdir(), 'sunday-excalidraw-'));
  const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  try {
    const page=await browser.newPage({ viewport:{width:1280,height:800} });
    page.setDefaultTimeout(10000);
    await page.addInitScript(() => { window.showOpenFilePicker=async()=>[{kind:'file',name:'test.png',getFile:async()=>new File([Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO7+8iUAAAAASUVORK5CYII='),c=>c.charCodeAt(0))],'test.png',{type:'image/png'})}]; });
    await page.goto(base + '/');
    await page.evaluate(async ({base,workspace})=> {
      document.body.innerHTML = '<main id="acceptance" style="height:750px"></main>';
      const root=document.getElementById('acceptance');
      const mod=await import(base+'/api/core/plugin-system/excalidraw/assets/ui/page.mjs');
      const rpc=async(method,params)=>{
        const response=await fetch(base+'/api/core/plugin-system/excalidraw/rpc',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({method,params:{...params,work_root:workspace}})});
        const result=await response.json(); if (!response.ok || result.status!=='ok') throw Error(result.payload?.error || 'operation failed'); return result.payload;
      };
      window.disposeExcalidraw=mod.mount(root,{rpc,signal:new AbortController().signal,addStyle(css){const e=document.createElement('style');e.textContent=css;document.head.appendChild(e);return()=>e.remove()}});
    },{base,workspace});
    await page.getByTestId('toolbar-rectangle').waitFor();
    await page.getByRole('button',{name:'新建',exact:true}).click();
    await page.getByTestId('toolbar-rectangle').click();
    const box=await page.locator('.excalidraw canvas.interactive').boundingBox();
    await page.mouse.move(box.x+800,box.y+450); await page.mouse.down(); await page.mouse.move(box.x+950,box.y+550,{steps:5}); await page.mouse.up();
    await page.evaluate(()=>new Promise(done=>requestAnimationFrame(()=>requestAnimationFrame(done))));
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.getByRole('status').getByText('已保存').waitFor();
    const saved=JSON.parse(await readFile(join(workspace,'drawing.excalidraw'),'utf8'));
    assert.ok(saved.elements.some(e=>e.type==='rectangle'&&!e.isDeleted));
    await page.getByTestId('dropdown-menu-button').last().click();
    await page.getByTestId('toolbar-embeddable').last().click();
    const mermaidDialog=page.getByRole('dialog');
    await mermaidDialog.locator('.cm-content').fill('flowchart LR\n A[开始] --> B[完成]');
    const insert=mermaidDialog.getByRole('button',{name:/插入/});
    await page.waitForFunction(()=>{const e=[...document.querySelectorAll('[role=dialog] button')].find(x=>x.textContent.includes('插入'));return e&&!e.disabled});
    await insert.click();await page.waitForFunction(()=>!document.querySelector('[role=dialog]'));
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.getByRole('status').getByText('已保存').waitFor();
    const withMermaid=JSON.parse(await readFile(join(workspace,'drawing.excalidraw'),'utf8'));
    assert.ok(withMermaid.elements.some(e=>e.type==='arrow'&&!e.isDeleted));
    await page.getByRole('button',{name:'打开',exact:true}).click();
    await page.getByRole('status').getByText('已打开').waitFor();
    const markdown = '---\nexcalidraw-plugin: parsed\n---\n用户备注\n\n# Excalidraw Data\n\n## Text Elements\n\n## Drawing\n```json\n{"type":"excalidraw","version":2,"elements":[],"appState":{},"files":{}}\n```\n%%\n末尾\n';
    await writeFile(join(workspace,'original.excalidraw.md'),markdown);
    const previousCanvas = await page.locator('.excalidraw canvas.interactive').elementHandle();
    await page.getByLabel('工作区文件路径').fill('original.excalidraw.md');
    await page.getByRole('button',{name:'打开',exact:true}).click();
    await page.getByRole('status').getByText('已打开', {exact:true}).waitFor();
    await previousCanvas.waitForElementState('hidden');
    await page.locator('.excalidraw canvas.interactive').waitFor();
    await page.getByTestId('toolbar-rectangle').click();
    await page.waitForFunction(() => document.querySelector('[data-testid=toolbar-rectangle]')?.getAttribute('aria-pressed') === 'true');
    const mdBox=await page.locator('.excalidraw canvas.interactive').boundingBox();
    await page.mouse.move(mdBox.x+800,mdBox.y+450); await page.mouse.down(); await page.mouse.move(mdBox.x+950,mdBox.y+550,{steps:5}); await page.mouse.up();
    await page.evaluate(()=>new Promise(done=>requestAnimationFrame(()=>requestAnimationFrame(done))));
    await page.getByTestId('toolbar-text').click();
    await page.locator('.excalidraw canvas.interactive').click({position:{x:700,y:250}});
    await page.keyboard.insertText('中文验证'); await page.keyboard.press('Escape');
    await page.getByTestId('dropdown-menu-button').first().click();
    await page.getByRole('menuitem',{name:'从系统导入'}).click();
    await page.locator('.excalidraw canvas.interactive').click({position:{x:800,y:300}});
    await page.evaluate(()=>new Promise(done=>requestAnimationFrame(()=>requestAnimationFrame(done))));
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.getByRole('status').getByText('已保存').waitFor();
    const written=await readFile(join(workspace,'original.excalidraw.md'),'utf8');
    assert.match(written, /中文验证 \^[a-zA-Z0-9]{8}/);
    const attachment=written.match(/## Embedded Files\n[a-zA-Z0-9_-]+: \[\[(\.excalidraw-assets\/[0-9a-f]{64}\.png)\]\]/);
    assert.ok(attachment); assert.ok((await readFile(join(workspace,attachment[1]))).length>0);
    await page.getByRole('button',{name:'打开',exact:true}).click();
    await page.getByRole('status').getByText('已打开', {exact:true}).waitFor();
    assert.ok(written.includes('用户备注') && written.endsWith('```\n%%\n末尾\n'));
    assert.ok(JSON.parse(written.split('```json\n')[1].split('\n```')[0]).elements.some(e=>e.type==='rectangle'));
    await writeFile(join(workspace,'external.png'),await readFile(join(workspace,attachment[1])));
    await writeFile(join(workspace,'external.excalidraw.md'),written.replace(attachment[1],'external.png'));
    await page.getByLabel('工作区文件路径').fill('external.excalidraw.md');
    await page.getByRole('button',{name:'打开',exact:true}).click();
    await page.getByRole('status').getByText('已打开', {exact:true}).waitFor();
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.getByRole('status').getByText('已保存').waitFor();
    assert.match(await readFile(join(workspace,'external.excalidraw.md'),'utf8'), /\[\[external\.png\]\]/);
    await page.getByLabel('工作区文件路径').fill('new.excalidraw.md');
    await page.getByRole('button',{name:'新建',exact:true}).click();
    await page.getByRole('status').getByText('新画图尚未保存').waitFor();
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.getByRole('status').getByText('已保存').waitFor();
    const createdMarkdown=await readFile(join(workspace,'new.excalidraw.md'),'utf8');
    assert.match(createdMarkdown,/excalidraw-plugin: parsed/);assert.match(createdMarkdown,/```compressed-json/);
    await page.getByRole('button',{name:'打开',exact:true}).click();
    await page.getByRole('status').getByText('已打开', {exact:true}).waitFor();
    await page.evaluate(()=>window.disposeExcalidraw());
    assert.equal(await page.locator('.excalidraw').count(),0);
  } finally { await browser.close(); await rm(workspace,{recursive:true,force:true}); }
});
